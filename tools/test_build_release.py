"""Offline tests for the deterministic package-install fixture builder."""

from __future__ import annotations

import hashlib
from pathlib import Path
import tarfile
import tempfile
import unittest

from build_release import DATA, MODULES, ReleaseError, build, metadata


class ReleaseBuilderTests(unittest.TestCase):
    """Protect the package distribution contract without needing Emacs."""

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="luau-package-build-")
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        for name in (*MODULES, *DATA):
            (self.root / name).write_text(f";;; {name}\n", encoding="utf-8")
        (self.root / "luau-mode.el").write_text(
            ';;; luau-mode.el --- Luau\n;; Version: 0.7.0\n'
            ';; Package-Requires: ((emacs "31.1"))\n', encoding="utf-8")

    def test_package_contents_are_allowlisted_and_rooted(self):
        """No tests, benchmarks, generated bytecode or developer scripts ship."""
        (self.root / "private.el").write_text("secret")
        output = build(self.root)
        with tarfile.open(output) as archive:
            names = [item.name for item in archive]
            expected = {"luau-mode-0.7.0"}
            expected.update(f"luau-mode-0.7.0/{name}" for name in (*MODULES, *DATA))
            expected.add("luau-mode-0.7.0/luau-mode-pkg.el")
            self.assertEqual(set(names), expected)
            self.assertEqual(len(names), len(expected))
            self.assertIn(b'(define-package "luau-mode" "0.7.0"',
                          archive.extractfile("luau-mode-0.7.0/luau-mode-pkg.el").read())

    def test_descriptor_avoids_spurious_native_compiler_warnings(self):
        """Mark the required package descriptor as non-compilable metadata."""
        output = build(self.root)
        with tarfile.open(output) as archive:
            descriptor = archive.extractfile(
                "luau-mode-0.7.0/luau-mode-pkg.el").read().decode()
        self.assertIn("lexical-binding: t", descriptor.splitlines()[0])
        self.assertIn("no-byte-compile: t", descriptor.splitlines()[0])
        self.assertIn('(define-package "luau-mode" "0.7.0"', descriptor)

    def test_same_sources_produce_identical_archive(self):
        """Rebuilds have byte-for-byte identical tar digests."""
        first = build(self.root).read_bytes()
        second = build(self.root).read_bytes()
        self.assertEqual(hashlib.sha256(first).digest(), hashlib.sha256(second).digest())

    def test_version_is_derived_from_source(self):
        """Avoid manually maintained, out-of-sync package versions."""
        source = self.root / "luau-mode.el"
        source.write_text(source.read_text().replace("0.7.0", "0.9.1"))
        self.assertEqual(metadata(self.root)[0], "0.9.1")
        self.assertEqual(build(self.root).name, "luau-mode-0.9.1.tar")

    def test_malformed_headers_fail_closed(self):
        """Never build packages without explicit requirements or version."""
        source = self.root / "luau-mode.el"
        source.write_text(source.read_text().replace("Package-Requires", "Requires"))
        with self.assertRaisesRegex(ReleaseError, "Version/Package-Requires"):
            build(self.root)

    def test_missing_module_fails_closed(self):
        """Reject a partial distribution before invoking Emacs."""
        (self.root / "luau-lsp.el").unlink()
        with self.assertRaisesRegex(ReleaseError, "luau-lsp.el"):
            build(self.root)

    def test_symlink_module_fails_closed(self):
        """Never silently ship content through a distribution symlink."""
        (self.root / "luau-lsp.el").unlink()
        (self.root / "luau-lsp.el").symlink_to("README.md")
        with self.assertRaisesRegex(ReleaseError, "unsafe"):
            build(self.root)


if __name__ == "__main__":
    unittest.main()
